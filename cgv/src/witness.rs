//! Witness tests (CG-1.37, rules WX-1 to WX-11 in
//! `intent/2026-10-21-witness-tests-spec.md`): one pytest module per error
//! whose target is a Django or pydantic field, running the field's own
//! validation on the error's counterexample.

use std::collections::{BTreeMap, HashMap};
use std::path::Path;

use crate::db::{FieldLibrary, FieldOrigin};
use crate::report::{CheckResult, CheckerOutput, NodeRef};

/// First line of every file the generator writes (WX-5); WX-6 removes only
/// files that start with it.
pub const MARKER: &str = "# Generated by crosscheck-contracts --witness-tests (CG-1.37). Do not edit.";
pub const HELPER_FILE: &str = "_cgv_witness.py";
const MODULE_PREFIX: &str = "test_cgv_witness_";
const HELPER_SOURCE: &str = include_str!("witness_helper.py");

/// A node as the checker's JSON names it.
type NodeKey = (String, String, i64);

fn key(node: &NodeRef) -> NodeKey {
    (node.name.clone(), node.file.clone(), node.line)
}

/// The `field_origins` rows of a contract database, by node.
pub fn read_origins(db: &Path) -> rusqlite::Result<HashMap<NodeKey, FieldOrigin>> {
    let conn = rusqlite::Connection::open_with_flags(db, rusqlite::OpenFlags::SQLITE_OPEN_READ_ONLY)?;
    let mut stmt = conn.prepare(
        "SELECT n.name, n.source_file, n.source_line, f.library, f.module, f.class_name, f.field_name, \
         f.validated \
         FROM field_origins f JOIN nodes n ON n.id = f.node_id",
    )?;
    let rows = stmt.query_map([], |row| {
        let library: String = row.get(3)?;
        Ok((
            (row.get(0)?, row.get(1)?, row.get(2)?),
            FieldOrigin {
                library: FieldLibrary::parse(&library).ok_or_else(|| {
                    rusqlite::Error::InvalidColumnType(3, library.clone(), rusqlite::types::Type::Text)
                })?,
                module: row.get(4)?,
                class_name: row.get(5)?,
                field_name: row.get(6)?,
                validated: row.get(7)?,
            },
        ))
    })?;
    rows.collect()
}

/// Why a witness error gets no module (WX-2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum NotReached {
    TargetNotEnforced,
    CounterexampleNotRecognised,
}

impl NotReached {
    fn as_str(self) -> &'static str {
        match self {
            NotReached::TargetNotEnforced => "target not enforced at run time",
            NotReached::CounterexampleNotRecognised => "counterexample text not recognised",
        }
    }
}

#[derive(Debug, PartialEq, Eq)]
pub struct WitnessModule {
    pub file_name: String,
    pub contents: String,
}

#[derive(Debug, Default)]
pub struct Plan {
    pub modules: Vec<WitnessModule>,
    /// Every module that declares a Django field, sorted: the helper gives
    /// each an app before importing any (WX-9).
    pub django_modules: Vec<String>,
    pub not_reached: BTreeMap<NotReached, usize>,
}

/// Whether `text` is a counterexample of WX-4, and if so whether it is
/// fractional.
pub fn recognise(text: &str) -> Option<bool> {
    let digits = |s: &str| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit());
    let integer = |s: &str| digits(s.strip_prefix('-').unwrap_or(s));
    if text == "None" || integer(text) {
        return Some(false);
    }
    if let Some(n) = text.strip_prefix("\"x\" * ") {
        return digits(n).then_some(false);
    }
    if let Some(d) = text.strip_prefix("Decimal(\"").and_then(|r| r.strip_suffix("\")")) {
        return match d.split_once('.') {
            None => integer(d).then_some(false),
            Some((whole, frac)) => (integer(whole) && digits(frac)).then_some(true),
        };
    }
    let inner = text.strip_prefix('"')?.strip_suffix('"')?;
    let mut chars = inner.chars();
    while let Some(c) = chars.next() {
        match c {
            '\\' => {
                let width = match chars.next()? {
                    '\\' | '"' => 0,
                    'x' => 2,
                    'u' => 4,
                    'U' => 8,
                    _ => return None,
                };
                for _ in 0..width {
                    if !matches!(chars.next()?, '0'..='9' | 'a'..='f') {
                        return None;
                    }
                }
            }
            '"' => return None,
            ' '..='~' => {}
            _ => return None,
        }
    }
    Some(false)
}

/// `<slug>` of WX-5.
fn slug(name: &str) -> String {
    let mut out = String::new();
    for c in name.to_lowercase().chars() {
        if c.is_ascii_lowercase() || c.is_ascii_digit() {
            out.push(c);
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    out.trim_matches('_').to_string()
}

/// A Python string literal (JSON's escapes are valid Python).
fn py_str(s: &str) -> String {
    serde_json::to_string(s).expect("a string serialises")
}

fn py_field(origin: &FieldOrigin) -> String {
    format!(
        "({}, {}, {}, {})",
        py_str(origin.library.as_str()),
        py_str(&origin.module),
        py_str(&origin.class_name),
        py_str(&origin.field_name)
    )
}

/// One line of the header comment, with line breaks flattened.
fn comment(text: &str) -> String {
    text.replace(['\r', '\n'], " ")
}

/// The source test of WX-8, or the comment that withholds it.
fn source_part(result: &CheckResult, source: &FieldOrigin) -> String {
    if result.source_guarantee.starts_with("range ") {
        return "\n# test_source_accepts_counterexample is withheld: the source guarantee is a range \
                bound, which\n# scaledBound may have rounded to the weaker side (CG-1.40 item 5).\n"
            .to_string();
    }
    format!(
        "\nSOURCE = {}\n\n\ndef test_source_accepts_counterexample():\n    \
         check_source(SOURCE, TARGET, COUNTEREXAMPLE, FRACTIONAL)\n",
        py_field(source)
    )
}

fn render(result: &CheckResult, counterexample: &str, fractional: bool, target: &FieldOrigin, source: Option<&FieldOrigin>) -> String {
    let path = result.path.join(" -> ");
    let site = result
        .site
        .as_ref()
        .map(|s| format!(" ({}:{})", s.file, s.line))
        .unwrap_or_default();
    let header = [
        format!("Error: {path}{site}"),
        format!("Source guarantee: {}", result.source_guarantee),
        format!("Target requirement: {}", result.target_requirement),
        format!(
            "Target field: {} {}.{}.{} ({}:{})",
            target.library.as_str(),
            target.module,
            target.class_name,
            target.field_name,
            result.target.file,
            result.target.line
        ),
        format!("Counterexample: {counterexample}"),
    ];
    let mut out = format!("{MARKER}\n#\n");
    for line in header {
        out.push_str(&format!("# {}\n", comment(&line)));
    }
    out.push_str(
        "#\n\
         # Strength. The Lean checker proves the counterexample is admitted by the source bound\n\
         # and rejected by the target bound, relative to the translated constraints. This\n\
         # module runs the target field's own validation on that one value. A failure marked\n\
         # CGV-WITNESS REJECTED is tested evidence, on this one value and the library version the\n\
         # message names, that the target field rejects it. A pass means the library accepted\n\
         # the value, which is no evidence for the error. Neither shows that the code produces\n\
         # the value (CG-1.39).\n\n\
         from decimal import Decimal  # noqa: F401\n\n\
         from _cgv_witness import check_source, check_target  # noqa: F401\n\n",
    );
    out.push_str(&format!(
        "COUNTEREXAMPLE = {counterexample}\nFRACTIONAL = {}\nTARGET = {}\n\n\n\
         def test_target_accepts_counterexample():\n    \
         check_target(TARGET, COUNTEREXAMPLE, FRACTIONAL)\n",
        if fractional { "True" } else { "False" },
        py_field(target)
    ));
    if let Some(source) = source {
        out.push_str(&source_part(result, source));
    }
    out
}

/// The modules of a run (WX-2, WX-5, WX-7, WX-8).
pub fn plan(output: &CheckerOutput, origins: &HashMap<NodeKey, FieldOrigin>) -> Plan {
    let mut plan = Plan::default();
    let django: std::collections::BTreeSet<&str> = origins
        .values()
        .filter(|o| o.library == FieldLibrary::Django)
        .map(|o| o.module.as_str())
        .collect();
    plan.django_modules = django.into_iter().map(str::to_string).collect();
    let validated = |node: &NodeRef| origins.get(&key(node)).filter(|o| o.validated);
    for result in &output.results {
        let Some(counterexample) = result.counterexample.as_deref() else {
            continue;
        };
        if result.severity != "error" {
            continue;
        }
        let Some(target) = validated(&result.target) else {
            *plan.not_reached.entry(NotReached::TargetNotEnforced).or_default() += 1;
            continue;
        };
        let Some(fractional) = recognise(counterexample) else {
            *plan.not_reached.entry(NotReached::CounterexampleNotRecognised).or_default() += 1;
            continue;
        };
        let number = plan.modules.len() + 1;
        plan.modules.push(WitnessModule {
            file_name: format!("{MODULE_PREFIX}{number:03}_{}.py", slug(&result.target.name)),
            contents: render(result, counterexample, fractional, target, validated(&result.source)),
        });
    }
    plan
}

fn is_generated(path: &Path) -> std::io::Result<bool> {
    let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
        return Ok(false);
    };
    let ours = name == HELPER_FILE || (name.starts_with(MODULE_PREFIX) && name.ends_with(".py"));
    if !ours || !path.is_file() {
        return Ok(false);
    }
    let text = std::fs::read(path)?;
    Ok(text.starts_with(MARKER.as_bytes()) && text.get(MARKER.len()) == Some(&b'\n'))
}

/// Clear the generator's earlier files from `dir` and write the plan's
/// modules, with the helper when there is at least one (WX-5, WX-6).
pub fn write(dir: &Path, plan: &Plan, app_root: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dir)?;
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if is_generated(&path)? {
            std::fs::remove_file(&path)?;
        }
    }
    if plan.modules.is_empty() {
        return Ok(());
    }
    let root = std::path::absolute(app_root)?;
    let helper = format!(
        "{MARKER}\n\nAPP_ROOT = {}\nDJANGO_MODULES = [{}]\n\n{HELPER_SOURCE}",
        py_str(&root.to_string_lossy()),
        plan.django_modules.iter().map(|m| py_str(m)).collect::<Vec<_>>().join(", ")
    );
    std::fs::write(dir.join(HELPER_FILE), helper)?;
    for module in &plan.modules {
        std::fs::write(dir.join(&module.file_name), &module.contents)?;
    }
    Ok(())
}

/// The stderr line of WX-1.
pub fn summary(dir: &Path, plan: &Plan) -> String {
    let n = plan.modules.len();
    let mut line = format!(
        "wrote {n} witness test module{} to {}",
        if n == 1 { "" } else { "s" },
        dir.display()
    );
    let skipped: usize = plan.not_reached.values().sum();
    if skipped > 0 {
        let reasons: Vec<String> = plan
            .not_reached
            .iter()
            .map(|(reason, count)| format!("{count} {}", reason.as_str()))
            .collect();
        line.push_str(&format!(
            "; {skipped} witness error{} not yet reached ({})",
            if skipped == 1 { "" } else { "s" },
            reasons.join(", ")
        ));
    }
    line
}

#[cfg(test)]
mod tests {
    use super::*;

    fn origin(library: FieldLibrary) -> FieldOrigin {
        FieldOrigin {
            library,
            module: "shop.models".into(),
            class_name: "Order".into(),
            field_name: "code".into(),
            validated: matches!(library, FieldLibrary::Django | FieldLibrary::Pydantic),
        }
    }

    fn result(source: &str, target: &str, guarantee: &str, counterexample: Option<&str>) -> CheckResult {
        let node = |name: &str, line| NodeRef {
            file: "shop/models.py".into(),
            line,
            name: name.into(),
        };
        CheckResult {
            status: "inconsistent".into(),
            severity: "error".into(),
            source: node(source, 3),
            target: node(target, 7),
            path: vec![source.into(), target.into()],
            hop: vec![source.into(), target.into()],
            site: None,
            source_guarantee: guarantee.into(),
            target_requirement: "length ≤ 6".into(),
            verification_level: "EXTRACTED".into(),
            suggestion: String::new(),
            counterexample: counterexample.map(str::to_string),
        }
    }

    fn output(results: Vec<CheckResult>) -> CheckerOutput {
        CheckerOutput {
            summary: Default::default(),
            results,
            exit_code: 1,
        }
    }

    fn origins(entries: &[(&str, i64, FieldLibrary)]) -> HashMap<NodeKey, FieldOrigin> {
        entries
            .iter()
            .map(|&(name, line, library)| ((name.into(), "shop/models.py".into(), line), origin(library)))
            .collect()
    }

    #[test]
    fn recognises_each_counterexample_form_of_wt2_to_wt7() {
        for (text, fractional) in [
            ("None", false),
            ("3", false),
            ("-1", false),
            ("\"x\" * 12", false),
            ("Decimal(\"0.0001\")", true),
            ("Decimal(\"-5.5\")", true),
            ("Decimal(\"11\")", false),
            ("\"zz\"", false),
            ("\"a\\\\b\\\"c\\x0a\\u00e9\\U0001f600\"", false),
        ] {
            assert_eq!(recognise(text), Some(fractional), "{text}");
        }
    }

    #[test]
    fn rejects_text_outside_the_grammar() {
        for text in [
            "",
            "x",
            "\"x\" * -1",
            "Decimal(\"1e5\")",
            "Decimal(\".5\")",
            "\"a\" + __import__(\"os\")",
            "\"a\"\"b\"",
            "\"\\n\"",
            "\"\\x0A\"",
            "\"é\"",
            "\"a\nb\"",
            "1.5",
        ] {
            assert_eq!(recognise(text), None, "{text:?}");
        }
    }

    #[test]
    fn slug_lowercases_and_collapses_other_characters() {
        assert_eq!(slug("AuditLog.short_ref"), "auditlog_short_ref");
        assert_eq!(slug("billing.records.Invoice.total"), "billing_records_invoice_total");
        assert_eq!(slug("__X--y__"), "x_y");
    }

    #[test]
    fn one_module_per_error_on_a_validated_field() {
        let out = output(vec![
            result("f", "Order.code", "length ≤ 12", Some("\"x\" * 12")),
            result("g", "Order.code", "length ≤ 9", Some("\"x\" * 9")),
            result("h", "Plain.code", "length ≤ 9", Some("\"x\" * 9")),
            result("k", "Order.code", "length ≤ 9", None),
        ]);
        let plan = plan(
            &out,
            &origins(&[("Order.code", 7, FieldLibrary::Django), ("Plain.code", 7, FieldLibrary::Dataclass)]),
        );
        let names: Vec<_> = plan.modules.iter().map(|m| m.file_name.as_str()).collect();
        assert_eq!(names, ["test_cgv_witness_001_order_code.py", "test_cgv_witness_002_order_code.py"]);
        assert_eq!(plan.not_reached, BTreeMap::from([(NotReached::TargetNotEnforced, 1)]));
        let m = &plan.modules[0].contents;
        assert!(m.starts_with(&format!("{MARKER}\n")));
        assert!(m.contains("COUNTEREXAMPLE = \"x\" * 12\nFRACTIONAL = False\n"));
        assert!(m.contains("TARGET = (\"django\", \"shop.models\", \"Order\", \"code\")"));
        assert!(m.contains("def test_target_accepts_counterexample():"));
        assert!(!m.contains("test_source_accepts_counterexample"));
    }

    #[test]
    fn an_unvalidated_pydantic_field_gets_no_module() {
        let out = output(vec![result("f", "Order.code", "nullable", Some("None"))]);
        let mut origins = origins(&[("Order.code", 7, FieldLibrary::Pydantic)]);
        origins.values_mut().for_each(|o| o.validated = false);
        let plan = plan(&out, &origins);
        assert!(plan.modules.is_empty());
        assert_eq!(plan.not_reached, BTreeMap::from([(NotReached::TargetNotEnforced, 1)]));
        assert!(plan.django_modules.is_empty());
    }

    #[test]
    fn a_warning_or_an_unrecognised_counterexample_gets_no_module() {
        let mut warning = result("f", "Order.code", "length ≤ 12", Some("\"x\" * 12"));
        warning.severity = "warning".into();
        let out = output(vec![warning, result("g", "Order.code", "length ≤ 12", Some("os.system()"))]);
        let plan = plan(&out, &origins(&[("Order.code", 7, FieldLibrary::Pydantic)]));
        assert!(plan.modules.is_empty());
        assert_eq!(plan.not_reached, BTreeMap::from([(NotReached::CounterexampleNotRecognised, 1)]));
    }

    #[test]
    fn a_source_field_gets_a_source_test_unless_its_guarantee_is_a_range() {
        let out = output(vec![
            result("Src.code", "Order.code", "length ≤ 12", Some("\"x\" * 12")),
            result("Src.code", "Order.code", "range ≤ 5.5", Some("Decimal(\"5.5\")")),
        ]);
        let plan = plan(
            &out,
            &origins(&[("Order.code", 7, FieldLibrary::Pydantic), ("Src.code", 3, FieldLibrary::Django)]),
        );
        let [length, range] = &plan.modules[..] else {
            panic!("two modules expected");
        };
        assert!(length.contents.contains("def test_source_accepts_counterexample():"));
        assert!(length.contents.contains("SOURCE = (\"django\""));
        assert!(!range.contents.contains("def test_source_accepts_counterexample"));
        assert!(range.contents.contains("# test_source_accepts_counterexample is withheld"));
        assert!(range.contents.contains("FRACTIONAL = True"));
    }

    #[test]
    fn header_lines_cannot_break_out_of_the_comment() {
        let mut r = result("f", "Order.code", "choices in [a\nimport os]", Some("\"a\""));
        r.target_requirement = "choices in [b\r\nx = 1]".into();
        let plan = plan(&output(vec![r]), &origins(&[("Order.code", 7, FieldLibrary::Django)]));
        let m = &plan.modules[0].contents;
        assert!(m.contains("# Source guarantee: choices in [a import os]\n"));
        assert!(m.contains("# Target requirement: choices in [b  x = 1]\n"));
        assert!(!m.lines().any(|l| l == "import os" || l.starts_with("x = 1")));
    }

    #[test]
    fn write_replaces_only_generated_files() {
        let dir = tempfile::TempDir::new().unwrap();
        let own = dir.path().join("test_cgv_witness_009_mine.py");
        std::fs::write(&own, "def test_mine(): pass\n").unwrap();
        std::fs::write(dir.path().join("conftest.py"), "").unwrap();
        let stale = dir.path().join("test_cgv_witness_007_old.py");
        std::fs::write(&stale, format!("{MARKER}\nold\n")).unwrap();

        let out = output(vec![result("f", "Order.code", "length ≤ 12", Some("\"x\" * 12"))]);
        let plan = plan(&out, &origins(&[("Order.code", 7, FieldLibrary::Django)]));
        write(dir.path(), &plan, Path::new("/app")).unwrap();
        let mut names: Vec<String> = std::fs::read_dir(dir.path())
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        names.sort();
        assert_eq!(
            names,
            ["_cgv_witness.py", "conftest.py", "test_cgv_witness_001_order_code.py", "test_cgv_witness_009_mine.py"]
        );
        let helper = std::fs::read_to_string(dir.path().join(HELPER_FILE)).unwrap();
        assert!(helper.starts_with(&format!("{MARKER}\n\nAPP_ROOT = \"/app\"\nDJANGO_MODULES = [\"shop.models\"]\n")));

        write(dir.path(), &Plan::default(), Path::new("/app")).unwrap();
        let left: Vec<String> = std::fs::read_dir(dir.path())
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        assert_eq!(left.len(), 2, "{left:?}");
        assert!(own.exists());
    }

    #[test]
    fn summary_counts_modules_and_reasons() {
        let mut plan = Plan::default();
        assert_eq!(summary(Path::new("w"), &plan), "wrote 0 witness test modules to w");
        plan.modules.push(WitnessModule {
            file_name: "a".into(),
            contents: String::new(),
        });
        plan.not_reached.insert(NotReached::TargetNotEnforced, 2);
        assert_eq!(
            summary(Path::new("w"), &plan),
            "wrote 1 witness test module to w; 2 witness errors not yet reached (2 target not enforced at run time)"
        );
    }
}
