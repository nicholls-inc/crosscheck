#!/usr/bin/env python3
"""Run the witness tests of every fixture against pinned Django and pydantic (CG-1.37).

`contracts check --witness-tests` writes one pytest module per error whose target is a
Django or pydantic field. Each module asserts that the target field accepts the error's
counterexample, so it fails, with a message that starts CGV-WITNESS REJECTED, when the
library rejects it (WX-7 in intent/2026-10-21-witness-tests-spec.md).

Subcommands (run from cgv/):
  run       For every fixture with an expected.json, write its witness modules and run
            them with each pinned environment. Exit 0 only when every target test failed
            with CGV-WITNESS REJECTED or was skipped with CGV-WITNESS WITHHELD, every source
            test passed, the fixture witness_tests has a rejected module of every
            counterexample kind and of both libraries, and witness_tests_clean has no
            module. Exit 1 otherwise, naming each module and outcome, and 2 when the
            harness itself fails.
  selftest  Write the modules of witness_tests, replace the counterexample of one module
            per kind with a value its field accepts, and exit 0 only when the run then
            flags exactly those modules.

  python3 scripts/witness_tests.py run
  python3 scripts/witness_tests.py selftest

Needs python3.12 (or --python), a release build of the CLI and the Lean checker, and
network access to the package index on the first run. The tests themselves run offline.
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

CGV = Path(__file__).resolve().parent.parent
ENVIRONMENTS = {
    "django42": CGV / "scripts" / "witness-requirements-django42.txt",
    "django52": CGV / "scripts" / "witness-requirements-django52.txt",
}
CLI = CGV / "target" / "release" / "crosscheck-contracts"
CHECKER = CGV / "prover" / ".lake" / "build" / "bin" / "contract-graph-checker"
MARKER = "# Generated by crosscheck-contracts --witness-tests (CG-1.37). Do not edit."
KINDS = ("length", "precision", "range", "range_min", "choices", "nullability")
LIBRARIES = ("django", "pydantic")

# Fixtures whose model module imports a package the environments do not pin. Their
# modules must fail with exactly this import error: a module that cannot be imported on
# its own is not yet reached (intent/2026-10-21-witness-tests.md). Any other outcome fails
# the run, so the entry is removed when the package is pinned.
IMPORT_GAPS = {
    "r6_pydantic_forms": "pydantic_settings",
    "r7_external_alias": "opentelemetry",
}

# For the self-test: a value each target field of witness_tests accepts, one per kind.
MUTANTS = {
    "models.Account.code": '"abc"',
    "records.Order.amount": 'Decimal("0.12")',
    "models.Account.level": "10",
    "records.Order.discount": "0",
    "models.Account.status": '"a"',
    "records.Order.label": '"l"',
}


class HarnessError(Exception):
    pass


def kind_of(guarantee):
    for prefix, kind in (("length ", "length"), ("precision ", "precision"), ("range ≤", "range"),
                         ("range ≥", "range_min"), ("choices ", "choices"), ("nullable", "nullability")):
        if guarantee.startswith(prefix):
            return kind
    return None


def header(module):
    """The source guarantee and the target field's library and name, from a module's header."""
    text = module.read_text(encoding="utf-8")
    guarantee = re.search(r"^# Source guarantee: (.*)$", text, re.M).group(1)
    library, name = re.search(r"^# Target field: (\w+) (\S+)", text, re.M).groups()
    return kind_of(guarantee), library, name


def ensure_venv(name, python, index_url, work):
    requirements = ENVIRONMENTS[name]
    digest = hashlib.sha256(requirements.read_bytes()).hexdigest()
    venv = work / f"venv-{name}"
    marker = venv / "requirements.sha256"
    if marker.is_file() and marker.read_text() == digest:
        return venv / "bin" / "python"
    shutil.rmtree(venv, ignore_errors=True)
    subprocess.run([python, "-m", "venv", str(venv)], check=True)
    subprocess.run([str(venv / "bin" / "python"), "-m", "pip", "install", "--quiet", "--disable-pip-version-check",
                    "--require-hashes", "--index-url", index_url, "-r", str(requirements)], check=True)
    marker.write_text(digest)
    return venv / "bin" / "python"


def generate(fixture, out):
    """Write the witness modules of one fixture into `out`; return them, sorted."""
    run = subprocess.run(
        [str(CLI), "contracts", "check", str(fixture) + "/", "--lean-checker", str(CHECKER),
         "--output-db", str(out.parent / f"{fixture.name}.sqlite"), "--witness-tests", str(out)],
        capture_output=True, text=True)
    if run.returncode not in (0, 1) or "witness test module" not in run.stderr:
        raise HarnessError(f"{fixture.name}: contracts check exited {run.returncode}\n{run.stderr}")
    return sorted(out.glob("test_cgv_witness_*.py"))


def outcomes(python, modules_dir, report):
    """Run pytest on one fixture's modules; return {(module, test): (outcome, message)}."""
    env = {k: v for k, v in os.environ.items() if k not in ("DJANGO_SETTINGS_MODULE", "PYTHONPATH")}
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    run = subprocess.run([str(python), "-m", "pytest", "-q", "-p", "no:cacheprovider", f"--junitxml={report}",
                          str(modules_dir)], capture_output=True, text=True, env=env, cwd=modules_dir)
    if not report.is_file():
        raise HarnessError(f"pytest wrote no report for {modules_dir}:\n{run.stdout}\n{run.stderr}")
    results = {}
    for case in ET.parse(report).getroot().iter("testcase"):
        module = case.get("classname", "").rsplit(".", 1)[-1] + ".py"
        outcome, message = "passed", ""
        for tag in ("failure", "error", "skipped"):
            node = case.find(tag)
            if node is not None:
                outcome, message = tag, node.get("message", "")
        results[(module, case.get("name"))] = (outcome, message)
    return results


def verdict(test, outcome, message, import_gap=None):
    """None when the outcome is the one WX-7 or WX-8 states, or the listed import gap,
    else why not."""
    message = message.removeprefix("Failed: ")
    if import_gap is not None:
        if outcome == "failure" and message.startswith(f"ModuleNotFoundError: No module named '{import_gap}'"):
            return None
        return f"listed in IMPORT_GAPS, but {outcome}{': ' + message.splitlines()[0] if message else ''}"
    if test == "test_target_accepts_counterexample":
        if outcome == "failure" and message.startswith("CGV-WITNESS REJECTED"):
            return None
        if outcome == "skipped" and "CGV-WITNESS WITHHELD" in message:
            return None
    elif test == "test_source_accepts_counterexample" and outcome == "passed":
        return None
    return f"{outcome}{': ' + message.splitlines()[0] if message else ''}"


def check_fixture(python, fixture, work, config):
    """Return (problems, rejected modules) of one fixture under one environment."""
    out = work / "modules" / fixture.name
    shutil.rmtree(out, ignore_errors=True)
    modules = generate(fixture, out)
    if not modules:
        return [], []
    results = outcomes(python, out, work / f"{fixture.name}-{config}.xml")
    problems, rejected = [], []
    import_gap = IMPORT_GAPS.get(fixture.name)
    for module in modules:
        tests = {test: r for (m, test), r in results.items() if m == module.name}
        if "test_target_accepts_counterexample" not in tests:
            problems.append(f"{module.name}: no target test ran ({tests or 'collection failed'})")
        for test, (outcome, message) in sorted(tests.items()):
            why = verdict(test, outcome, message, import_gap)
            if why:
                problems.append(f"{module.name}::{test}: {why}")
            elif test == "test_target_accepts_counterexample" and outcome == "failure" and not import_gap:
                rejected.append(module)
    return problems, rejected


def run_all(args, work, fixtures):
    failed = False
    for config in args.configs:
        python = ensure_venv(config, args.python, args.index_url, work)
        for fixture in fixtures:
            problems, rejected = check_fixture(python, fixture, work, config)
            written = sorted((work / "modules" / fixture.name).glob("test_cgv_witness_*.py"))
            if fixture.name == "witness_tests":
                found = {header(m) for m in rejected}
                for kind in KINDS:
                    if not any(k == kind for k, _, _ in found):
                        problems.append(f"no rejected module of kind {kind}")
                for library in LIBRARIES:
                    if not any(lib == library for _, lib, _ in found):
                        problems.append(f"no rejected module of library {library}")
            if fixture.name == "witness_tests_clean" and written:
                problems.append(f"wrote {len(written)} module(s), expected none")
            for p in problems:
                print(f"FAIL {config} {fixture.name}: {p}")
            if written or problems:
                print(f"{config} {fixture.name}: {len(written)} module(s), {len(rejected)} rejected, "
                      f"{len(problems)} problem(s)")
            failed |= bool(problems)
    return failed


def cmd_run(args):
    work = Path(args.work_dir).resolve()
    work.mkdir(parents=True, exist_ok=True)
    fixtures = sorted(p.parent for p in (CGV / "test_fixtures").glob("*/expected.json"))
    failed = run_all(args, work, fixtures)
    print("witness tests: " + ("FAILED" if failed else "every module failed as stated or was withheld"))
    return 1 if failed else 0


def cmd_selftest(args):
    work = Path(args.work_dir).resolve() / "selftest"
    work.mkdir(parents=True, exist_ok=True)
    fixture = CGV / "test_fixtures" / "witness_tests"
    status = 0
    for config in args.configs:
        python = ensure_venv(config, args.python, args.index_url, work.parent)
        out = work / "modules" / fixture.name
        shutil.rmtree(out, ignore_errors=True)
        mutated = set()
        for module in generate(fixture, out):
            _, _, name = header(module)
            if name in MUTANTS:
                text = module.read_text(encoding="utf-8")
                new = re.sub(r"^COUNTEREXAMPLE = .*$", lambda _: f"COUNTEREXAMPLE = {MUTANTS[name]}", text, count=1,
                             flags=re.M)
                module.write_text(new, encoding="utf-8")
                mutated.add(module.name)
        if len(mutated) != len(MUTANTS):
            print(f"FAIL {config}: mutated {sorted(mutated)}, expected one module per entry of MUTANTS")
            status = 1
            continue
        results = outcomes(python, out, work / f"selftest-{config}.xml")
        flagged = {m for (m, test), (outcome, message) in results.items() if verdict(test, outcome, message)}
        if flagged != mutated:
            print(f"FAIL {config}: the run flagged {sorted(flagged)}, expected exactly {sorted(mutated)}")
            status = 1
        else:
            print(f"{config}: the run flags each of the {len(mutated)} mutated modules and no other")
    return status


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["run", "selftest"])
    parser.add_argument("--python", default=shutil.which("python3.12") or "python3")
    parser.add_argument("--index-url", default="https://pypi.org/simple")
    parser.add_argument("--work-dir", default=str(CGV / "target" / "witness-tests"))
    parser.add_argument("--configs", type=lambda s: s.split(","), default=list(ENVIRONMENTS))
    args = parser.parse_args()
    for path in (CLI, CHECKER):
        if not path.is_file():
            print(f"missing {path} (build it first)", file=sys.stderr)
            return 2
    try:
        return cmd_run(args) if args.command == "run" else cmd_selftest(args)
    except (HarnessError, subprocess.CalledProcessError) as e:
        print(f"harness error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
